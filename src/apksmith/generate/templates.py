"""
Dart/Flutter templates for project generation.

Kept as plain string templates rather than a template engine because there is
no runtime dependency to install and the output is trivially readable. Every
placeholder uses ``{{name}}`` and is filled by :func:`render`.

These templates are the part that must be correct without any model
involvement, so they are written defensively: valid Dart, no external packages
beyond `http`, and no code that will fail to compile.
"""

from __future__ import annotations

import re
from typing import Any

_PLACEHOLDER = re.compile(r"\{\{\s*(\w+)\s*\}\}")


def render(template: str, **values: Any) -> str:
    """Replace {{name}} placeholders. Unknown placeholders become empty."""

    def sub(match: re.Match[str]) -> str:
        key = match.group(1)
        value = values.get(key, "")
        return value if isinstance(value, str) else str(value)

    out = _PLACEHOLDER.sub(sub, template)
    # Collapse triple blank lines, which fall out of optional blocks.
    return re.sub(r"\n{3,}", "\n\n", out).strip() + "\n"


