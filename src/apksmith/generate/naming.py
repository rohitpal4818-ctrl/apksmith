_INVALID_IDENT = re.compile(r"[^A-Za-z0-9_]")


def snake(value: str) -> str:
    """Convert any label into a valid Dart snake_case identifier."""
    cleaned = _INVALID_IDENT.sub("_", value.strip())
    cleaned = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", cleaned)
    cleaned = re.sub(r"_+", "_", cleaned).strip("_").lower()
    if not cleaned:
        cleaned = "item"
    if cleaned[0].isdigit():
        cleaned = f"v_{cleaned}"
    return cleaned


def pascal(value: str) -> str:
    """Convert any label into a valid Dart UpperCamelCase identifier."""
    parts = snake(value).split("_")
    return "".join(p[:1].upper() + p[1:] for p in parts if p) or "Item"


def singular(value: str) -> str:
    """Best-effort singularisation, so `expenses` becomes `expense`.

    English pluralisation is genuinely hard, and an over-clever rule set is
    worse than a simple one here: `expenses` -> `expens` produces an identifier
    that reads as a typo in the generated code.

    So this is deliberately conservative:

    * ``-ies`` -> ``-y``   (categories -> category)
    * ``-ss``  -> unchanged (address)
    * ``-s``   -> dropped  (expenses -> expense, items -> item)

    The failure mode is the occasional slightly odd word (``boxes`` ->
    ``boxe``), which nobody notices, rather than a mangled identifier.
    """
    v = value.strip().lower()
    if not v:
        return "item"
    if v.endswith("ies") and len(v) > 4:
        return v[:-3] + "y"
    if v.endswith("ss"):
        return v
    if v.endswith("s") and len(v) > 1:
        return v[:-1]
    return v


def dart_string(value: str) -> str:
    """Quote a value safely for embedding in Dart source."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace("$", "\\$")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
    )
    return f'"{escaped}"'
