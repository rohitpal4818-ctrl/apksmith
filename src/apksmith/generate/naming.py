"""
Code generation: BehaviourSpec -> a runnable project.

Design stance
-------------
A language model asked to "write this app" from a behaviour spec will produce
something plausible and wrong. What actually works is a split:

    Deterministic   Project scaffolding, configuration, routing, theme, data
                    classes, API client. These are fully determined by the
                    spec, so they are generated by code and are correct by
                    construction.

    Model-assisted  Screen layout and state handling, where judgement is
                    needed. Optionally delegated to an LLM, and clearly
                    marked as such in the output.

The output is therefore always *runnable*, even with no API key, because the
critical scaffolding never depends on a model. This is also the honest answer
to "generate an app from an APK": you get a working shell with the observed
structure and a clear list of what still needs real logic.

The Flutter target was chosen because one codebase covers Android and iOS,
which makes for a considerably better demonstration than Kotlin-only output.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from ..fileio import write_text


class SpecError(Exception):
    """The spec cannot be turned into a project."""


@dataclass
class GeneratedFile:
    """One file of a generated project, held in memory until ``write``.

    ``origin`` is what the generated project's README uses to separate what is
    real from what is a placeholder, so it is part of the contract rather than
    a debugging nicety.
    """

    path: str
    content: str
    #: ``scaffold`` = correct by construction, ``model`` = LLM assisted,
    #: ``stub`` = structure only, logic left to the developer.
    origin: str = "scaffold"
    note: str = ""


@dataclass
class GenerationResult:
    """Everything produced from one spec, plus the honest gaps.

    Warnings are things that look wrong in the input; open questions are things
    the spec did not say and a human has to decide. Both are surfaced by the
    CLI, because silently inventing either would be worse than saying nothing.
    """

    files: list[GeneratedFile] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    #: Things the spec did not tell us, which a human must supply.
    open_questions: list[str] = field(default_factory=list)

    def write(self, root: Path, overwrite: bool = False) -> list[Path]:
        """Write every file under ``root``. Returns the paths written.

        Existing files are skipped unless ``overwrite`` is set, so re-running
        against a directory with hand edits in it does not discard them.
        """
        written: list[Path] = []
        for generated_file in self.files:
            dest = root / generated_file.path
            if dest.exists() and not overwrite:
                continue
            write_text(dest, generated_file.content)
            written.append(dest)
        return written

    def summary(self) -> str:
        """One line, e.g. ``41 scaffold, 3 stub``, for the CLI to echo."""
        by_origin: dict[str, int] = {}
        for generated_file in self.files:
            by_origin[generated_file.origin] = by_origin.get(generated_file.origin, 0) + 1
        return ", ".join(
            f"{count} {origin}" for origin, count in sorted(by_origin.items())
        )


