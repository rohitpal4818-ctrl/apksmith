"""
M3 and M5: code generation and evaluation.

    apksmith generate --spec reports/understanding.json --out build/recon
    apksmith evaluate reports/evaluation.json --out reports/evaluation.md
"""

from __future__ import annotations

import json
from pathlib import Path

import typer

from .generate import build_flutter_project
from .understand.spec import BehaviourSpec

generate_cli = typer.Typer(
    name="generate", help="M3: behaviour spec -> runnable project.", no_args_is_help=True
)
evaluate_cli = typer.Typer(
    name="evaluate", help="M5: score specs against hand-written references.",
    no_args_is_help=True,
)


@generate_cli.command("run")
def generate_run(
    spec: Path = typer.Argument(..., exists=True, help="Behaviour spec JSON from M2"),
    out: Path = typer.Option(Path("build/reconstruction"), "--out", help="Output directory"),
    overwrite: bool = typer.Option(False, "--overwrite", help="Replace existing files"),
) -> None:
    """Generate a Flutter project from a behaviour specification.

    No API key needed. The scaffolding is generated by code; screen logic is
    left as explicit TODO markers rather than invented.
    """
    try:
        parsed = BehaviourSpec.model_validate(json.loads(spec.read_text(encoding="utf-8")))
    except (json.JSONDecodeError, ValueError) as exc:
        typer.secho(f"could not read spec: {exc}", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1)

    try:
        result = build_flutter_project(parsed)
    except ValueError as exc:
        typer.secho(f"cannot generate: {exc}", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1)

    written = result.write(out, overwrite=overwrite)

    typer.secho(f"generated {len(written)} files -> {out}", fg=typer.colors.GREEN)
    typer.echo(f"  {result.summary()}")

    for gf in result.files:
        marker = "*" if gf.path in {p.name for p in written} else " "
        typer.echo(f"  {marker} [{gf.origin:8}] {gf.path}")

    if result.warnings:
        typer.secho("\nwarnings", fg=typer.colors.YELLOW)
        for w in result.warnings:
            typer.echo(f"  - {w}")

    if result.open_questions:
        typer.secho("\nopen questions (analysis could not answer these)", fg=typer.colors.YELLOW)
        for q in result.open_questions:
            typer.echo(f"  - {q}")

    typer.secho(
        "\nthis is a scaffold. Screen behaviour, state and business rules are "
        "TODO. run `flutter pub get` inside the output to verify it compiles.",
        fg=typer.colors.CYAN,
    )


@evaluate_cli.command("run")
def evaluate_run(
    suite: Path = typer.Argument(..., exists=True, help="Reference suite JSON"),
    out: Path = typer.Option(Path("reports/evaluation.md"), "--out", help="Markdown report"),
) -> None:
    """Score generated specs against hand-written references."""
    from .evaluate import load_suite

    try:
        report = load_suite(suite)
    except (ValueError, KeyError, json.JSONDecodeError) as exc:
        typer.secho(f"could not load suite: {exc}", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1)

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report.to_markdown(), encoding="utf-8")

    typer.secho(f"evaluated {len(report.cases)} case(s) -> {out}", fg=typer.colors.GREEN)
    typer.echo(f"  mean F1 across cases: {report.mean_f1:.3f}")
    for name, value in report.per_metric().items():
        typer.echo(f"  {name:<26} {value:.3f}")
    typer.secho(
        "\nthese measure agreement with an independent human description, not "
        "truth. treat them as a regression signal.",
        fg=typer.colors.CYAN,
    )